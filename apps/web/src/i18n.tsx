interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (message: string, params?: MessageParams) => string;
}

const I18nContext = createContext<I18nValue>({
  locale: 'en',
  setLocale: () => undefined,
  t: (message) => message
});

function getInitialLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'zh' || stored === 'en') return stored;
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

function interpolate(message: string, params?: MessageParams): string {
  if (!params) return message;
  return message.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(params[key] ?? ''));
}

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  const setLocale = (next: Locale): void => {
    setLocaleState(next);
    if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, next);
  };

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
    }
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (message, params) => interpolate(locale === 'zh' ? (ZH_MESSAGES[message] ?? message) : message, params)
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

export const LanguageSwitcher: React.FC<{ compact?: boolean }> = ({ compact = false }) => {
  const { locale, setLocale } = useI18n();
  const nextLocale: Locale = locale === 'en' ? 'zh' : 'en';
  return (
    <button
      type="button"
      onClick={() => setLocale(nextLocale)}
      className={`sp-button-secondary inline-flex items-center gap-2 rounded-lg border border-slate-200 text-xs font-medium text-slate-500 transition-colors hover:bg-slate-50 ${compact ? 'px-3 py-2' : 'px-4 py-2.5'}`}
      title={locale === 'en' ? '切换为中文' : 'Switch to English'}
      aria-label={locale === 'en' ? '切换为中文' : 'Switch to English'}
    >
      <i className="fas fa-language text-xs"></i>
      {locale === 'en' ? '中文' : 'English'}
    </button>
  );
};
